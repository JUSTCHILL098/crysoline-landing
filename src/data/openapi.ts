export type EndpointType = {
  method: 'GET' | 'POST'
  path: string
  summary: string
  description: string
  tag: string
  params: { name: string; in: string; required: boolean; type: string }[]
}

// Build endpoints from tags
function animeEndpoints(slug: string, tag: string, hasServers = false): EndpointType[] {
  const base = `/api/v1/anime/${slug}`
  const eps: EndpointType[] = [
    { method: 'GET', path: `${base}/search`, summary: 'Search', description: `Search ${tag} for media by query string`, tag, params: [{ name: 'q', in: 'query', required: true, type: 'string' }] },
    { method: 'GET', path: `${base}/info/{id}`, summary: 'Info', description: `Get detailed info for a specific ${tag} item by ID`, tag, params: [{ name: 'id', in: 'path', required: true, type: 'string' }] },
    { method: 'GET', path: `${base}/episodes/{id}`, summary: 'Episodes', description: `Get episode list for a specific ${tag} anime entry`, tag, params: [{ name: 'id', in: 'path', required: true, type: 'string' }] },
  ]
  if (hasServers) {
    eps.push({ method: 'GET', path: `${base}/servers`, summary: 'Servers', description: `Get available streaming servers for an episode`, tag, params: [{ name: 'id', in: 'query', required: true, type: 'string' }, { name: 'episodeId', in: 'query', required: true, type: 'string' }] })
  }
  eps.push({ method: 'GET', path: `${base}/sources`, summary: 'Sources', description: `Get streaming sources for an episode`, tag, params: [{ name: 'id', in: 'query', required: true, type: 'string' }, { name: 'episodeId', in: 'query', required: true, type: 'string' }, { name: 'subType', in: 'query', required: false, type: 'string' }, { name: 'server', in: 'query', required: false, type: 'string' }] })
  return eps
}

